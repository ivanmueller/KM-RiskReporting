HEADER = """# Data dictionary - Stage 1 minimal schema (head migration `{head}`)

Generated by `riskparse gen-data-dictionary` from `src/riskparse/db/schema.py`; do not edit
by hand. The frozen migrations are the physical source of truth, and `tests/test_migrations.py`
asserts they match the schema, including CHECK constraint text.

Conventions: all timestamps are UTC (`*_utc`; timezone-aware values required, naive values
are rejected). Money/quantity use `NUMERIC(28,10)`. JSON is stored as text for portability.
Only portable DDL (PK, FK, UNIQUE, CHECK, index) is used until IT confirms the SQL engine.

> SQLite (local test adapter) stores NUMERIC as floating point; exact-decimal behaviour must
> be re-verified on the confirmed engine.
"""


def render() -> str:
    from riskparse.db import migrate
    missing = set(metadata.tables) ^ set(PURPOSE)
    if missing:
        raise RuntimeError(f"PURPOSE out of sync with schema: {sorted(missing)}")
    out = [HEADER.format(head=migrate.head_revision())]
    for name in PURPOSE:
        t = metadata.tables[name]
        out += [f"## `{name}`", "", PURPOSE[name], "",
                "| Column | Type | Null | Key / default |", "| --- | --- | --- | --- |"]
        pk = {c.name for c in t.primary_key.columns}
        for c in t.columns:
            keys = ["PK"] if c.name in pk else []
            keys += [f"FK → {fk.column.table.name}.{fk.column.name}" for fk in c.foreign_keys]
            if c.server_default is not None:
                keys.append(f"default `{c.server_default.arg}`")
            typ = "DATETIME (UTC)" if isinstance(c.type, UTCDateTime) else str(c.type)
            out.append(f"| `{c.name}` | {typ} | {'yes' if c.nullable else 'no'} | "
                       f"{', '.join(keys)} |")
        rules = []
        for con in sorted(t.constraints, key=lambda x: str(x.name)):
            if isinstance(con, UniqueConstraint):
                rules.append(f"- UNIQUE ({', '.join(col.name for col in con.columns)})")
            elif isinstance(con, CheckConstraint):
                rules.append(f"- CHECK `{con.name}`: `{con.sqltext}`")
        if rules:
            out += ["", "Rules:", ""] + rules
        out.append("")
    return "\n".join(out)
